import assert from 'node:assert/strict';
const storage = new Map();
globalThis.localStorage = { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value) };
const { read, write, normalize } = await import('../../../StickerApp.Shared/wwwroot/js/ui/browse-preferences.js');
write('library', { sort: 'oldest', favorites: 'yes', folder: 'f3b98ecb-aa15-4aaf-a90a-52f8a19a5601', search: 'private query' });
write('packs', { sort: 'newest', visibility: 'private', type: 'empty' });
write('pack-stickers', { sort: 'newest', type: 'animated' });
assert.equal(read('library').sort, 'oldest');
assert.equal(read('library').favorites, 'yes');
assert.equal(read('library').folder, 'f3b98ecb-aa15-4aaf-a90a-52f8a19a5601');
assert.equal(read('packs').sort, 'newest');
assert.equal(read('packs').visibility, 'private');
assert.equal(read('pack-stickers').type, 'animated');
assert.ok(!storage.get('stickers.browse.library').includes('private query'));
storage.set('stickers.browse.packs', '{broken');
assert.deepEqual(read('packs'), normalize('packs', {}));
assert.equal(normalize('library', { sort: 'newest', type: 'unknown', folder: 'deleted-or-invalid' }).sort, 'default');
assert.equal(normalize('library', []).folder, 'all');
write('library', { sort: 'oldest' });
assert.equal(read('library').favorites, 'all', 'reset filters replaces persisted values');
globalThis.localStorage = { getItem() { throw new Error('blocked'); }, setItem() { throw new Error('blocked'); } };
assert.equal(read('library').sort, 'default');
assert.doesNotThrow(() => write('packs', { sort: 'newest' }));
console.log('PASS browse preference persistence, independent views, reset, validation, corrupt/blocked storage and search exclusion');
